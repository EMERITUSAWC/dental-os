class VoiceScreenTests(Base):
    def test_off_until_a_manager_switches_it_on(self):
        c = self.login("dent")
        page = self.page(c, "/patients/1/perio/new")
        self.assertNotIn("voice-panel", page)
        self.assertNotIn("voice.js", page)
        m = self.login("mgr")
        r = self.post(m, "/settings", {"action": "voice_perio", "enabled": "1"}, follow_redirects=True)
        self.assertIn("Voice entry for gum charting", r.get_data(as_text=True))
        page = self.page(c, "/patients/1/perio/new")
        self.assertIn('id="voice-panel"', page)
        self.assertIn("/static/voice.js", page)
        self.assertIn('id="voice-text"', page)                                        # the typed way, which sends nothing anywhere
        self.assertIn('data-cloud="0"', page)                                         # sound stays on the computer unless the clinic says otherwise
        self.assertIn("pk_16_DB", page)                                               # the field names the script reads
        self.post(m, "/settings", {"action": "voice_perio"})
        self.assertNotIn("voice-panel", self.page(c, "/patients/1/perio/new"))

    def test_the_online_service_needs_its_own_yes_and_the_first_switch(self):
        m, c = self.login("mgr"), self.login("dent")
        self.post(m, "/settings", {"action": "voice_perio", "cloud": "1"})                       # cloud ticked but voice itself off
        self.assertNotIn("voice-panel", self.page(c, "/patients/1/perio/new"))
        self.post(m, "/settings", {"action": "voice_perio", "enabled": "1", "cloud": "1"})
        self.assertIn('data-cloud="1"', self.page(c, "/patients/1/perio/new"))
        self.post(m, "/settings", {"action": "voice_perio", "enabled": "1"})
        self.assertIn('data-cloud="0"', self.page(c, "/patients/1/perio/new"))
        conn = self.db()
        details = [r[0] for r in conn.execute("SELECT detail FROM audit_log WHERE action = 'settings.voice_perio' ORDER BY id").fetchall()]
        conn.close()
        self.assertEqual(details, ["off", "on, online allowed", "on"])

    def test_the_script_asks_the_browser_to_listen_on_the_computer(self):
        js = (ROOT / "dental_os" / "static" / "voice.js").read_text()
        self.assertIn("processLocally", js)
        self.assertIn("cloudOk", js)

    def test_only_a_manager_can_switch_it(self):
        self.assertEqual(self.post(self.login("dent"), "/settings", {"action": "voice_perio", "enabled": "1"}).status_code, 403)

    def test_the_script_is_served_and_needs_no_inline_code(self):
        c = self.login("dent")
        r = c.get("/static/voice.js")
        self.assertEqual(r.status_code, 200)
        self.assertIn("default-src 'self'", r.headers["Content-Security-Policy"])
        self.assertNotIn("script-src", r.headers["Content-Security-Policy"])
        self.assertNotIn("<script>", self.page(self.login("mgr"), "/settings"))

    def test_saving_a_chart_filled_in_by_voice_works_like_any_other(self):
        c = self.login("dent")
        r = self.post(c, "/patients/1/perio/new", {"pk_16_DB": "3", "pk_16_B": "2", "pk_16_MB": "3", "bl_16_B": "1", "rc_16_DB": "-1"}, follow_redirects=True)
        self.assertEqual(r.status_code, 200)
        self.assertEqual(self.one_value("SELECT COUNT(*) FROM perio_charts"), 1)

    def one_value(self, q):
        conn = self.db()
        v = conn.execute(q).fetchone()[0]
        conn.close()
        return v


