class TranslateTests(unittest.TestCase):
    def t(self, sql):
        return dbpg.translate(sql)

    def test_placeholders_and_percent_signs(self):
        self.assertEqual(self.t("SELECT * FROM a WHERE x = ? AND y LIKE '50%'"), "SELECT * FROM a WHERE x = %s AND y ILIKE '50%%'")
        self.assertEqual(self.t("SELECT '?' FROM a WHERE x = ?"), "SELECT '?' FROM a WHERE x = %s")           # a question mark in a string stays

    def test_time_functions(self):
        self.assertEqual(self.t("SELECT datetime('now')"), "SELECT dos_now()")
        self.assertEqual(self.t("SELECT 1 WHERE at >= datetime('now', ?)"), "SELECT 1 WHERE at >= dos_now_mod(%s)")
        self.assertEqual(self.t("SELECT datetime(m.created_at, '+30 days')"), "SELECT dos_dt(m.created_at, '+30 days')")
        self.assertEqual(self.t("SELECT date(a.start_at)"), "SELECT dos_date(a.start_at)")
        self.assertEqual(self.t("SELECT CAST(strftime('%s', a.start_at) AS INTEGER)"), "SELECT CAST(dos_epoch(a.start_at) AS INTEGER)")
        self.assertEqual(self.t("SELECT strftime('%m-%d', dob)"), "SELECT substr(dob, 6, 5)")
        self.assertIn("update(", self.t("SELECT 1 FROM t WHERE update(x)").lower())                           # a word that merely ends in date( is left alone

    def test_insert_or_ignore(self):
        self.assertEqual(self.t("INSERT OR IGNORE INTO t(a) VALUES (?)"), "INSERT INTO t(a) VALUES (%s) ON CONFLICT DO NOTHING")
        with self.assertRaises(dbpg.Error):
            self.t("INSERT OR REPLACE INTO t(a) VALUES (?)")

    def test_scalar_max_and_min_but_not_the_aggregates(self):
        self.assertIn("GREATEST(a - b, 0)", self.t("SELECT SUM(MAX(a - b, 0)) FROM t"))
        self.assertIn("LEAST(a, b)", self.t("SELECT MIN(a, b) FROM t"))
        self.assertIn("MAX(created_at)", self.t("SELECT MAX(created_at) FROM t"))

    def test_null_safe_comparison(self):
        out = self.t("SELECT 1 WHERE a IS ? AND b IS NOT ? AND c IS NULL AND d IS NOT NULL")
        self.assertIn("a IS NOT DISTINCT FROM %s", out)
        self.assertIn("b IS DISTINCT FROM %s", out)
        self.assertIn("c IS NULL", out)
        self.assertIn("d IS NOT NULL", out)

    def test_null_ordering_matches_sqlite(self):
        out = self.t("SELECT a FROM t ORDER BY x DESC, y, z DESC LIMIT 3")
        self.assertIn("x DESC NULLS LAST, y NULLS FIRST, z DESC NULLS LAST LIMIT 3", out)
        self.assertIn("(SELECT b FROM u ORDER BY id DESC NULLS LAST LIMIT 1)", self.t("SELECT (SELECT b FROM u ORDER BY id DESC LIMIT 1) FROM t"))
        self.assertEqual(self.t("SELECT a FROM t ORDER BY a NULLS LAST").count("NULLS"), 1)

    def test_begin_immediate_becomes_a_lock(self):
        self.assertIn("pg_advisory_xact_lock", self.t("BEGIN IMMEDIATE"))

    def test_case_blind_matching(self):
        self.assertIn('COLLATE "nocase"', self.t("SELECT 1 WHERE name = ? COLLATE NOCASE"))
        self.assertIn("ILIKE", self.t("SELECT 1 WHERE name LIKE ? ESCAPE '\\'"))

    def test_schema_translation(self):
        out = dbpg.translate_ddl("CREATE TABLE a (\n  id INTEGER PRIMARY KEY,\n  clinic_id INTEGER PRIMARY KEY REFERENCES c(id),\n  n INTEGER NOT NULL DEFAULT 0,\n"
                                 "  at TEXT NOT NULL DEFAULT (datetime('now')),\n  u TEXT UNIQUE COLLATE NOCASE\n)")
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
        self.assertIn("clinic_id BIGINT PRIMARY KEY", out)                   # only a column called id counts up by itself
        self.assertIn("DEFAULT (dos_now())", out)
        self.assertNotIn("INTEGER", out)

    def test_the_whole_schema_translates_and_splits(self):
        text = (ROOT / "dental_os" / "schema.sql").read_text()
        statements = dbpg.split_script(text)
        self.assertGreater(len(statements), 100)
        for s in statements:
            out = dbpg.translate_ddl(s)
            for word in ("datetime(", "INTEGER", "AUTOINCREMENT", "PRAGMA"):
                self.assertNotIn(word, out, s[:60])

    def test_every_statement_in_the_code_translates(self):
        """Every SQL string in the services must pass through the translator without an error, so a construct it cannot handle is found here."""
        import ast
        bad = []
        for path in (ROOT / "dental_os").rglob("*.py"):
            if path.name == "dbpg.py":
                continue
            for node in ast.walk(ast.parse(path.read_text())):
                if isinstance(node, ast.Constant) and isinstance(node.value, str) and len(node.value) > 15 and not node.value.startswith(("http", "/")):
                    v = node.value
                    if v.lstrip().upper().startswith(("SELECT ", "INSERT ", "UPDATE ", "DELETE ")):
                        try:
                            dbpg.translate(v)
                        except dbpg.Error as exc:
                            bad.append((str(path.name), str(exc)[:80]))
        self.assertEqual(bad, [])

    def test_rows_act_like_sqlite_rows(self):
        r = dbpg.Row(["id", "Name"], (7, "Ama"))
        self.assertEqual((r[0], r["id"], r["name"], r[-1]), (7, 7, "Ama", "Ama"))
        self.assertEqual(r.keys(), ["id", "Name"])
        self.assertEqual(tuple(r), (7, "Ama"))
        self.assertEqual(dict(zip(r.keys(), r)), {"id": 7, "Name": "Ama"})
        self.assertEqual(r, (7, "Ama"))
        with self.assertRaises(IndexError):
            r["nope"]

    def test_sums_stay_whole_numbers(self):
        import decimal
        self.assertEqual(dbpg._plain(decimal.Decimal("1500")), 1500)
        self.assertIsInstance(dbpg._plain(decimal.Decimal("1500")), int)
        self.assertEqual(dbpg._plain(decimal.Decimal("2.5")), 2.5)

    def test_a_database_address_is_recognised(self):
        self.assertTrue(dbpg.is_url("postgresql://u:p@h/db"))
        self.assertTrue(dbpg.is_url("postgres://u@h/db"))
        self.assertFalse(dbpg.is_url("/var/data/dental.sqlite"))


@unittest.skipUnless(dbmeta.ON_PG, "needs a PostgreSQL server: run the suite with DENTAL_OS_TEST_PG set")
class OnPostgresTests(Base):
    def test_a_failed_statement_does_not_spoil_the_transaction(self):
        conn = self.db()
        conn.execute("INSERT INTO tax_rates(clinic_id, name, kind, rate_bp) VALUES (1,'Same','rate',100)")
        with self.assertRaises(dbpg.IntegrityError) as ctx:
            conn.execute("INSERT INTO tax_rates(clinic_id, name, kind, rate_bp) VALUES (1,'Same','rate',100)")
        self.assertIn("UNIQUE constraint failed", str(ctx.exception))
        self.assertEqual(conn.execute("SELECT COUNT(*) FROM tax_rates WHERE name = 'Same'").fetchone()[0], 1)     # the first insert is still there
        conn.rollback()
        conn.close()

    def test_user_names_do_not_care_about_capitals(self):
        conn = self.db()
        self.assertIsNotNone(conn.execute("SELECT id FROM users WHERE username = ?", ("MGR",)).fetchone())
        with self.assertRaises(dbpg.IntegrityError):
            conn.execute("INSERT INTO users(clinic_id, username, display_name, role, password_hash) VALUES (1,'MGR','X','manager','x')")
        conn.rollback()
        conn.close()

    def test_empty_values_sort_first_going_up_and_last_going_down_like_sqlite(self):
        conn = self.db()
        conn.execute("UPDATE patients SET email = NULL WHERE id = 1")
        conn.execute("UPDATE patients SET email = 'b@x.com' WHERE id = 2")
        up = [r[0] for r in conn.execute("SELECT id FROM patients WHERE clinic_id = 1 ORDER BY email, id").fetchall()]
        down = [r[0] for r in conn.execute("SELECT id FROM patients WHERE clinic_id = 1 ORDER BY email DESC, id").fetchall()]
        self.assertEqual(up[0], 1)
        self.assertEqual(down[-1], 1)
        conn.rollback()
        conn.close()

    def test_sums_come_back_as_integers_and_inserts_give_back_their_id(self):
        conn = self.db()
        cur = conn.execute("INSERT INTO tax_rates(clinic_id, name, kind, rate_bp) VALUES (1,'Big','rate',1)")
        self.assertIsInstance(cur.lastrowid, int)
        total = conn.execute("SELECT SUM(rate_bp) FROM tax_rates").fetchone()[0]
        self.assertIsInstance(total, int)
        conn.rollback()
        conn.close()

    def test_text_dates_compare_and_sort_like_sqlite(self):
        conn = self.db()
        self.assertEqual(conn.execute("SELECT dos_date(datetime('now'))").fetchone()[0], conn.execute("SELECT substr(datetime('now'),1,10)").fetchone()[0])
        later = conn.execute("SELECT datetime('now', '+2 days') > datetime('now')").fetchone()[0]
        self.assertTrue(later)
        self.assertEqual(conn.execute("SELECT strftime('%m-%d', '2001-04-23')").fetchone()[0], "04-23")
        self.assertEqual(conn.execute("SELECT CAST(strftime('%s', '1970-01-02 00:00:00') AS INTEGER)").fetchone()[0], 86400)
        conn.close()

    def test_the_booking_lock_is_taken_and_released(self):
        conn = self.db()
        self.assertFalse(conn.in_transaction)
        conn.execute("BEGIN IMMEDIATE")
        self.assertTrue(conn.in_transaction)
        conn.commit()
        self.assertFalse(conn.in_transaction)
        conn.close()


