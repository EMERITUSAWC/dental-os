@unittest.skipUnless(dbmeta.ON_PG, "needs a PostgreSQL server: run the suite with DENTAL_OS_TEST_PG set")
class CopyTests(unittest.TestCase):
    """A real SQLite file, filled by the app's own demo data, copied into a fresh PostgreSQL schema."""

    def test_a_sqlite_database_moves_across_whole(self):
        import os
        import sqlite3
        import tempfile
        from dental_os import db as dbmod, demo
        from dental_os.services import pgcopy
        tmp = tempfile.TemporaryDirectory()
        path = str(Path(tmp.name) / "from.sqlite")
        src = sqlite3.connect(path)
        src.row_factory = sqlite3.Row
        src.execute("PRAGMA foreign_keys = ON")
        dbmod.init_schema(src)
        src.execute("INSERT INTO clinics(name, country, currency, timezone, payment_methods) VALUES ('Copy Clinic','GH','GHS','Africa/Accra','cash')")
        demo.seed(src, 1)
        src.commit()
        # a self-pointing row, written the other way round (the guarantor comes after the dependant)
        src.execute("UPDATE patients SET guarantor_id = (SELECT MAX(id) FROM patients) WHERE id = (SELECT MIN(id) FROM patients)")
        src.commit()
        url = os.environ["DENTAL_OS_TEST_PG"]
        raw = dbpg.open_raw(url)
        raw.cursor().execute('DROP SCHEMA IF EXISTS "t_copytest" CASCADE')
        raw.cursor().execute('CREATE SCHEMA "t_copytest"')
        raw.commit()
        raw.close()
        dst = dbpg.connect(url, "t_copytest")
        try:
            counts = pgcopy.copy(src, dst)
            self.assertGreater(counts["patients"], 3)
            self.assertGreater(sum(counts.values()), 40)
            for table in ("clinics", "patients", "appointments", "procedures"):
                self.assertEqual(dst.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0], src.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0], table)
            a = src.execute("SELECT id, first_name, last_name, guarantor_id FROM patients ORDER BY id").fetchall()
            b = dst.execute("SELECT id, first_name, last_name, guarantor_id FROM patients ORDER BY id").fetchall()
            self.assertEqual([tuple(r) for r in a], [tuple(r) for r in b])
            new_id = dst.execute("INSERT INTO patients(clinic_id, first_name, last_name, phone) VALUES (1,'New','Person','+233200000000')").lastrowid
            self.assertGreater(new_id, max(r[0] for r in a))                              # the counter carried on after the copied ids
            with self.assertRaises(pgcopy.CopyError):
                pgcopy.copy(src, dst)                                                      # a second copy into a full database is refused
        finally:
            dst.rollback()
            dst.close()
            raw = dbpg.open_raw(url)
            raw.cursor().execute('DROP SCHEMA IF EXISTS "t_copytest" CASCADE')
            raw.commit()
            raw.close()
            src.close()
